// Unicode constants for key glyphs used in shortcut definitions and UI displays.

namespace Nota.Application.Input;

public static class KeyGlyphs
{
    public const char Cmd = '\u2318';        // ⌘
    public const char Option = '\u2325';     // ⌥
    public const char Ctrl = '\u2303';       // ⌃
    public const char Shift = '\u21E7';      // ⇧
    public const char Backspace = '\u232B';  // ⌫
    public const char Return = '\u21B5';     // ↵
}
